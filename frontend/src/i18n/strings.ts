export function translate(lang: Lang, key: keyof Dict | string, vars?: Record<string, string | number>): string {
  const raw = (dicts[lang] as any)[key] ?? (en as any)[key] ?? key;
  if (!vars) return raw;
  return Object.entries(vars).reduce((s, [k, v]) => s.split(`{${k}}`).join(String(v)), raw as string);
}
